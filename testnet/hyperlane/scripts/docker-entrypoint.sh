#!/bin/bash

# Deploys Hyperlane on both ev-reth (evolve) and celestia (celestiadev).
# To minimise proving time in the docker env in this repository we first deploy
# a noop ism stack on celestia and later overwrite this with a zk ism deployment
# (`make deploy-ism`). This ensures that the initial trusted root used in the zk
# ism is the same as the latest block's state root in ev-reth.
#
# EVM contract addresses are CREATE addresses, so they depend on the exact
# sequence of transactions the Hyperlane CLI sends, which changes between CLI
# versions. Nothing in git therefore hardcodes them: the committed registry
# holds no evolve addresses, every run deploys from a scratch copy of it, and
# the resulting addresses are written to ./generated (gitignored) for the
# relayer, the Makefile and ev-prover.

set -euo pipefail

cd /home/hyperlane
GENERATED=./generated
REGISTRY=$GENERATED/registry

# Wait for ev-node sequencer to be ready
echo "Waiting for ev-node sequencer to be ready..."
sleep 10

# HYP_KEY is the priv key of the EVM account used for Hyperlane contract deployment
export HYP_KEY=0x82bfcfadbf1712f6550d8d2c00a39f05b33ec78939d0167be2a737d691f33a6a
export HYP_KEY_COSMOSNATIVE=0x6e30efb1d3ebd30d1ba08c8d5fc9b190e08394009dc1dd787a69e60c33288a8c

echo "Preparing a scratch registry at $REGISTRY..."
mkdir -p "$GENERATED"
rm -rf "$REGISTRY"
cp -r ./registry "$REGISTRY"

echo "Using Hyperlane CLI $(hyperlane --version | tail -1) and registry:"
hyperlane registry list --registry "$REGISTRY"

echo "Deploying Hyperlane core on Evolve..."
hyperlane core deploy --chain evolve --config ./configs/evolve-core.yaml --registry "$REGISTRY" --yes
hyperlane core read --chain evolve --config "$GENERATED/evolve-core.yaml" --registry "$REGISTRY"

echo "Deploying Hyperlane core on Celestia..."
hyperlane core deploy --chain celestiadev --config ./configs/celestia-core.yaml --registry "$REGISTRY" --yes
hyperlane core read --chain celestiadev --config "$GENERATED/celestia-core.yaml" --registry "$REGISTRY"

echo "Deploying TIA warp route..."
hyperlane warp deploy --warp-route-id TIA --registry "$REGISTRY" --yes

# address KEY FILE prints the value of the top-level `KEY: "..."` entry of a registry addresses file.
address() {
  local value
  value=$(awk -v key="$1:" '$1 == key { v = $NF; gsub(/"/, "", v); print v }' "$2")
  if [ -z "$value" ]; then
    echo "Error: no $1 in $2" >&2
    exit 1
  fi
  echo "$value"
}

# warp_token CHAIN prints the addressOrDenom of the TIA warp token on CHAIN from the warp route config
# the CLI wrote to the scratch registry.
warp_token() {
  local config
  config=$(find "$REGISTRY/deployments/warp_routes/TIA" -name '*-config.yaml' | head -1)
  if [ -z "$config" ]; then
    echo "Error: no TIA warp route config under $REGISTRY/deployments/warp_routes/TIA" >&2
    exit 1
  fi
  local value
  value=$(awk -v chain="$1" '/addressOrDenom:/ { v = $NF; gsub(/"/, "", v) } $1 == "chainName:" && $2 == chain { print v; exit }' "$config")
  if [ -z "$value" ]; then
    echo "Error: no $1 token in $config" >&2
    exit 1
  fi
  echo "$value"
}

EVOLVE=$REGISTRY/chains/evolve/addresses.yaml
CELESTIA=$REGISTRY/chains/celestiadev/addresses.yaml

# Plain assignments so a missing value aborts the script under set -e.
EVOLVE_MAILBOX=$(address mailbox "$EVOLVE")
EVOLVE_MERKLE_TREE_HOOK=$(address merkleTreeHook "$EVOLVE")
EVOLVE_VALIDATOR_ANNOUNCE=$(address validatorAnnounce "$EVOLVE")
EVOLVE_WARP_TOKEN=$(warp_token evolve)
CELESTIA_MAILBOX=$(address mailbox "$CELESTIA")
CELESTIA_MERKLE_TREE_HOOK=$(address merkleTreeHook "$CELESTIA")
CELESTIA_IGP=$(address interchainGasPaymaster "$CELESTIA")
CELESTIA_WARP_TOKEN=$(warp_token celestiadev)

echo "Writing $GENERATED/deployed.env..."
cat > "$GENERATED/deployed.env" <<ENV
# Generated by hyperlane-init, do not edit. Source it (set -a) before running
# make targets that talk to the testnet or \`ev-prover init\`.
MAILBOX_CONTRACT_ADDRESS=$EVOLVE_MAILBOX
MERKLE_TREE_CONTRACT_ADDRESS=$EVOLVE_MERKLE_TREE_HOOK
EVOLVE_WARP_TOKEN=$EVOLVE_WARP_TOKEN
CELESTIA_MAILBOX_ADDRESS=$CELESTIA_MAILBOX
CELESTIA_WARP_TOKEN=$CELESTIA_WARP_TOKEN
ENV
cat "$GENERATED/deployed.env"

# The cosmos hyperlane module announces validators through the mailbox, so the relayer config
# points validatorAnnounce at the mailbox id on celestiadev.
echo "Rendering $GENERATED/relayer-config.json..."
jq \
  --arg evolveMailbox "$EVOLVE_MAILBOX" \
  --arg evolveMerkleTreeHook "$EVOLVE_MERKLE_TREE_HOOK" \
  --arg evolveValidatorAnnounce "$EVOLVE_VALIDATOR_ANNOUNCE" \
  --arg celestiaMailbox "$CELESTIA_MAILBOX" \
  --arg celestiaMerkleTreeHook "$CELESTIA_MERKLE_TREE_HOOK" \
  --arg celestiaIgp "$CELESTIA_IGP" \
  '.chains.evolve.mailbox = $evolveMailbox
   | .chains.evolve.merkleTreeHook = $evolveMerkleTreeHook
   | .chains.evolve.validatorAnnounce = $evolveValidatorAnnounce
   | .chains.celestiadev.mailbox = $celestiaMailbox
   | .chains.celestiadev.merkleTreeHook = $celestiaMerkleTreeHook
   | .chains.celestiadev.interchainGasPaymaster = $celestiaIgp
   | .chains.celestiadev.validatorAnnounce = $celestiaMailbox' \
  ./relayer-config.template.json > "$GENERATED/relayer-config.json"

echo "Hyperlane deployment complete."
